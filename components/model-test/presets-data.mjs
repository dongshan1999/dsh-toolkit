/**
 * 内置模型参数预设表（纯数据：不 import、不读盘、不发网络请求）。
 *
 * ── 这份数据是什么 ───────────────────────────────────────────────
 * 第三方 OpenAI 兼容 / Anthropic 兼容接口每次接新模型都要手填 temperature、
 * 思考档位、上下文窗口。这里按**归一化模型名**给出一张离线精选表：
 * 命中后由 presets.js 换算成 suggest 参数，或直接生成 llm-pi-ai 的 models 条目
 * （见 presets.js 的 providerSnippet）。
 *
 * 归一化口径由 presets.js 的 normalizeModelId() 决定，写 matches 时必须按它想：
 *   `volcengine/doubao-seed-2.0-pro` → `doubao-seed-2.0-pro`
 *   `openai/gpt-oss-120b`            → `gpt-oss-120b`
 *   `kimi-k3:fast`                   → `kimi-k3`      （`:` 之后整段丢弃）
 *   `Qwen3-235B@fp8`                 → `qwen3-235b-fp8`（`@` 变 `-`、转小写）
 *   `gemini-2.5-pro[1m]`             → `gemini-2.5-pro`（去掉尾缀 `[1m]`）
 * 因此 matches 一律写**小写、不带 provider 前缀**的正则片段，运行时按 `new RegExp(p,'i')` 编译。
 *
 * ── 数据来源与快照日期 ───────────────────────────────────────────
 * 快照日期：2026-10-19（models.dev 的 api.json 全量快照，232 个 provider）。
 * 厂商原生 provider 优先：openai / anthropic / google / deepseek / xai / moonshotai /
 * zai / zhipuai / alibaba / minimax / mistral / meta / llama / volcengine / stepfun /
 * tencent-tokenhub / xiaomi / cohere / ai21 / inception / perplexity / upstage。
 * openrouter / poe / vercel / jiekou 这类聚合商**只用来交叉印证**，不作为单一事实源
 * （它们经常漏字段、把 temperature 写成默认值）。
 *
 * ── 字段含义 ─────────────────────────────────────────────────────
 * id                族 id，全局唯一；也被 matchPreset 当作「精确 id 命中」用。
 * label             面板 / 生成 YAML 里显示的名字。
 * vendor            厂商 key，与 models.dev 的 provider id 对齐（便于同步时比对）。
 * matches           正则字符串数组，编译后对小写归一化 id 做 test()。
 *                   要求：**互斥**。presets.js 取第一个命中即 break，但自检要求
 *                   任何一个真实 id 只能被一个族命中，靠 order 兜底是不允许的。
 * order             小者优先（具体族必须排在泛族前面，例如 gpt-5.3-codex-spark
 *                   排在 gpt-5 系之前）。
 * supportsTemperature  false = 该模型**不接受** temperature 参数。此时必须同时把
 *                   suggest.temperature 设为 null；anthropic-messages 协议要靠
 *                   compat.supportsTemperature 才肯省略温度，写错会 400。
 * reasoning.mode    'effort' —— 厂商给离散档位（low/medium/high/...）
 *                   'budget' —— 厂商收思考预算 token 数（min/max）
 *                   'toggle' —— 只有开/关，没有任何档位
 *                   'none'   —— 不支持思考
 * reasoning.levels  只允许 DSH pi-ai 的 7 个档位 id：
 *                   off / minimal / low / medium / high / xhigh / max
 *                   （pi-ai THINKING_LEVELS；xhigh、max 必须在 wire 里显式映射，
 *                   否则适配器的 thinkingLevelMap 会把它们当 null = 不支持）
 * reasoning.default 推荐档；必须是 levels 里的元素（'none' 模式为 null）。
 * reasoning.wire    档位 id → 线上真实拼写。厂商用 none/disabled/enabled 等词时，
 *                   在这里说清映射，exportPresetYaml 会原样写进 reasoningEfforts。
 * contextWindow     上下文窗口（token），来自 models.dev 的 limit.context。
 * maxTokens         输出上限（token），来自 limit.output。
 * suggest           推荐值；temperature 为 null 表示不发温度。
 * source            该族主要依据的 URL。
 * note              中文一句话，写清最容易踩的那个约束。
 *
 * ── 怎么维护 ─────────────────────────────────────────────────────
 * 1. 拉一份新快照：curl -s https://models.dev/api.json > /tmp/models-dev.json
 * 2. 只改「仍在主流」的型号；models.dev 里 status=deprecated 的条目一律跳过。
 * 3. 改完必须跑：node tools/check-presets.mjs（若仓库没有，则用
 *    `node -e "import('./components/model-test/presets-data.mjs')..."` 自检：
 *    id 唯一、正则全部可编译、真实模型 id 每个只命中一个族）。
 * 4. 新增族时先想清楚「order 让谁先」以及「和已有正则是否重叠」——重叠了就收窄。
 *
 * 时间基准：2026-10。表里只收当前（2026-10）仍被广泛使用的型号。
 */

